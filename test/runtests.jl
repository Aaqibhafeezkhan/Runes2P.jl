# Time of every test file, printed at the end of the suite. It holds the
# compilation of what the file is the first to use.
const FILE_TIMES = Pair{String,Float64}[]
function timed_include(file)
    elapsed = @elapsed Base.include(@__MODULE__, joinpath(@__DIR__, file))
    push!(FILE_TIMES, file => elapsed)
    return nothing
end

function print_file_times()
    total = sum(last, FILE_TIMES; init=0.0)
    println("Time per test file, ", round(total / 60; digits=1), " minutes in all:")
    for (file, elapsed) in sort(FILE_TIMES; by=last, rev=true)
        println(rpad(file, 44), lpad(round(elapsed; digits=1), 8), " s", lpad(round(100 * elapsed / total; digits=1), 7), " %")
    end
end

